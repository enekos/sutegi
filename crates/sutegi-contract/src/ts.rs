use std::collections::BTreeMap;
use std::fmt::Write;

use crate::registry::{ChannelSpec, Kind, Procedure};
use crate::ty::{Def, Field, Shape, Type, Variant, VariantShape};
use crate::Registry;

const RESERVED: &[&str] = &[
    "ContractError",
    "ContractErrorBody",
    "ClientOptions",
    "Streamed",
    "ChannelSocket",
    "ChannelHandle",
    "ChannelPush",
    "TypedChannel",
    "Client",
];

const RUNTIME: &str = include_str!("runtime.ts");

const CHANNEL_RUNTIME: &str = include_str!("channel_runtime.ts");

pub fn render(reg: &Registry) -> String {
    let mut out = String::with_capacity(8 * 1024);
    out.push_str(
        "// Generated by sutegi-contract from the app's registered contract. Do not edit.\n\n",
    );
    for def in reg.defs() {
        assert!(
            !RESERVED.contains(&def.name.as_str()),
            "contract type {:?} clashes with a name the TypeScript client exports; rename it with #[contract(rename = \"...\")]",
            def.name
        );
        render_def(&mut out, def);
    }
    out.push_str(RUNTIME);
    render_client(&mut out, reg);
    if reg.channels().iter().any(ChannelSpec::is_typed) {
        out.push_str(CHANNEL_RUNTIME);
        render_channels(&mut out, reg.channels());
    }
    out
}

pub fn type_expr(ty: &Type) -> String {
    match ty {
        Type::Unit => "null".to_string(),
        Type::Bool => "boolean".to_string(),
        Type::Int | Type::Float => "number".to_string(),
        Type::String => "string".to_string(),
        Type::Any => "unknown".to_string(),
        Type::Option(inner) => format!("{} | null", type_expr(inner)),
        Type::List(inner) => match **inner {
            Type::Option(_) => format!("({})[]", type_expr(inner)),
            _ => format!("{}[]", type_expr(inner)),
        },
        Type::Map(inner) => format!("Record<string, {}>", type_expr(inner)),
        Type::Ref(name) => name.clone(),
    }
}

fn quote(s: &str) -> String {
    sutegi_json::Json::str(s).to_string()
}

fn is_ident(s: &str) -> bool {
    let mut chars = s.chars();
    matches!(chars.next(), Some(c) if c.is_ascii_alphabetic() || c == '_' || c == '$')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
}

fn key(s: &str) -> String {
    if is_ident(s) {
        s.to_string()
    } else {
        quote(s)
    }
}

fn jsdoc(out: &mut String, indent: &str, doc: &str) {
    if doc.is_empty() {
        return;
    }
    let doc = doc.replace("*/", "*\\/");
    let lines: Vec<&str> = doc.lines().collect();
    if lines.len() == 1 {
        let _ = writeln!(out, "{indent}/** {} */", lines[0].trim());
    } else {
        let _ = writeln!(out, "{indent}/**");
        for line in lines {
            let _ = writeln!(out, "{indent} * {}", line.trim_end());
        }
        let _ = writeln!(out, "{indent} */");
    }
}

fn fields_body(out: &mut String, fields: &[Field], indent: &str) {
    for f in fields {
        jsdoc(out, indent, &f.doc);
        let opt = if f.required { "" } else { "?" };
        let _ = writeln!(out, "{indent}{}{opt}: {};", key(&f.name), type_expr(&f.ty));
    }
}

fn inline_fields(fields: &[Field]) -> String {
    let mut s = String::new();
    for f in fields {
        let opt = if f.required { "" } else { "?" };
        let _ = write!(s, " {}{opt}: {};", key(&f.name), type_expr(&f.ty));
    }
    s
}

fn render_def(out: &mut String, def: &Def) {
    jsdoc(out, "", &def.doc);
    match &def.shape {
        Shape::Struct(fields) => {
            let _ = writeln!(out, "export interface {} {{", def.name);
            fields_body(out, fields, "  ");
            out.push_str("}\n\n");
        }
        Shape::Alias(inner) => {
            let _ = writeln!(out, "export type {} = {};\n", def.name, type_expr(inner));
        }
        Shape::Enum(variants) => {
            let names: Vec<String> = variants.iter().map(|v| quote(&v.name)).collect();
            let _ = writeln!(out, "export type {} = {};", def.name, names.join(" | "));
            let _ = writeln!(
                out,
                "export const {}Values = [{}] as const;\n",
                def.name,
                names.join(", ")
            );
        }
        Shape::Union { tag, variants } => {
            let _ = writeln!(out, "export type {} =", def.name);
            for (i, v) in variants.iter().enumerate() {
                jsdoc(out, "  ", &v.doc);
                let end = if i + 1 == variants.len() { ";" } else { "" };
                let _ = writeln!(out, "  | {}{end}", union_arm(tag, v));
            }
            out.push('\n');
        }
    }
}

fn union_arm(tag: &str, v: &Variant) -> String {
    let head = format!("{}: {}", key(tag), quote(&v.name));
    match &v.shape {
        VariantShape::Unit => format!("{{ {head} }}"),
        VariantShape::Struct(fields) => format!("{{ {head};{} }}", inline_fields(fields)),
        VariantShape::Newtype(inner) => format!("({{ {head} }} & {})", type_expr(inner)),
    }
}

#[derive(Default)]
struct Tree<'a> {
    leaf: Option<&'a Procedure>,
    children: BTreeMap<&'a str, Tree<'a>>,
}

fn render_client(out: &mut String, reg: &Registry) {
    let procedures = reg.procedures();
    let mut root = Tree::default();
    for p in procedures {
        let mut node = &mut root;
        for seg in p.name.split('.') {
            node = node.children.entry(seg).or_default();
        }
        node.leaf = Some(p);
    }
    out.push_str("\nexport function createClient(options: ClientOptions = {}) {\n");
    out.push_str("  const rt = runtime(options);\n");
    out.push_str("  return ");
    render_tree(out, reg, &root, 1);
    out.push_str(";\n}\n\nexport type Client = ReturnType<typeof createClient>;\n");
}

fn render_tree(out: &mut String, reg: &Registry, node: &Tree<'_>, depth: usize) {
    let indent = "  ".repeat(depth + 1);
    let close = "  ".repeat(depth);
    out.push_str("{\n");
    for (name, child) in &node.children {
        if let Some(p) = child.leaf {
            jsdoc(out, &indent, &p.doc);
            let _ = write!(out, "{indent}{}: ", key(name));
            render_leaf(out, reg, p);
            out.push_str(",\n");
        } else {
            let _ = write!(out, "{indent}{}: ", key(name));
            render_tree(out, reg, child, depth + 1);
            out.push_str(",\n");
        }
    }
    out.push_str(&close);
    out.push('}');
}

fn input_type(p: &Procedure) -> Option<String> {
    let unbound: Vec<String> = p
        .unbound_params()
        .map(|n| format!(" {}: string | number;", key(n)))
        .collect();
    let extra = (!unbound.is_empty()).then(|| format!("{{{} }}", unbound.concat()));
    match (&p.input, extra) {
        (Type::Unit, None) => None,
        (Type::Unit, Some(e)) => Some(e),
        (ty, None) => Some(type_expr(ty)),
        (ty, Some(e)) => Some(format!("{} & {e}", type_expr(ty))),
    }
}

fn all_optional(reg: &Registry, p: &Procedure) -> bool {
    p.unbound_params().next().is_none()
        && reg
            .struct_fields(&p.input)
            .is_some_and(|fs| fs.iter().all(|f| !f.required))
}

fn render_leaf(out: &mut String, reg: &Registry, p: &Procedure) {
    let params: Vec<String> = p.path_params.iter().map(|n| quote(n)).collect();
    let params = format!("[{}]", params.join(", "));
    let (arg, value) = match input_type(p) {
        Some(t) if all_optional(reg, p) => (format!("input: {t} = {{}}"), "input"),
        Some(t) => (format!("input: {t}"), "input"),
        None => (String::new(), "undefined"),
    };
    let method = quote(&p.method);
    let path = quote(&p.path);
    let output = type_expr(&p.output);
    match (p.kind, &p.event) {
        (Kind::Stream, Some(event)) => {
            let _ = write!(
                out,
                "({arg}): Streamed<{event}, {output}> => rt.stream<{event}, {output}>({method}, {path}, {params}, {value})",
                event = type_expr(event)
            );
        }
        _ => {
            let _ = write!(
                out,
                "({arg}): Promise<{output}> => rt.call<{output}>({method}, {path}, {params}, {value})"
            );
        }
    }
}

fn render_channels(out: &mut String, channels: &[ChannelSpec]) {
    out.push_str("\nexport const channels = {\n");
    for c in channels.iter().filter(|c| c.is_typed()) {
        jsdoc(out, "  ", &c.doc);
        let mut args = vec!["socket: ChannelSocket".to_string()];
        let topic = if c.wildcard() {
            args.push("topic: string".to_string());
            format!("{} + topic", quote(c.prefix()))
        } else {
            quote(&c.pattern)
        };
        let (join_out, join_arg) = match &c.join {
            Some(j) => {
                args.push(format!("input: {}", type_expr(&j.payload)));
                (
                    j.reply.as_ref().map_or("null".to_string(), type_expr),
                    "input",
                )
            }
            None => ("unknown".to_string(), "{}"),
        };
        let emits: String = c
            .emits
            .iter()
            .map(|m| format!(" {}: {};", key(&m.event), type_expr(&m.payload)))
            .collect();
        let handles: String = c
            .handles
            .iter()
            .map(|m| {
                format!(
                    " {}: [{}, {}];",
                    key(&m.event),
                    type_expr(&m.payload),
                    m.reply.as_ref().map_or("null".to_string(), type_expr)
                )
            })
            .collect();
        let _ = writeln!(
            out,
            "  {}: ({}): TypedChannel<{join_out}, {{{emits} }}, {{{handles} }}> =>\n    typedChannel(socket.channel({topic}, {join_arg})),",
            key(&c.ident()),
            args.join(", ")
        );
    }
    out.push_str("};\n");
}
