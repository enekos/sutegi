//! Code generation: the SQL install script, the C glue, the control file,
//! the linker export list and the PGXS Makefile.

use std::fmt::Write as _;

use super::scan::Function;

macro_rules! emit {
    ($out:expr, $($fmt:tt)*) => {
        writeln!($out, $($fmt)*).expect("writing to a String cannot fail")
    };
}

/// Quotes a SQL identifier.
fn ident(s: &str) -> String {
    format!("\"{}\"", s.replace('"', "\"\""))
}

/// Quotes a SQL string literal.
fn literal(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}

/// The C symbol PostgreSQL calls for `f`.
pub(crate) fn c_symbol(f: &Function) -> String {
    format!("sx_fn_{}", f.rust_name)
}

fn signature_types(f: &Function) -> String {
    f.params
        .iter()
        .map(|p| p.sql_type)
        .collect::<Vec<_>>()
        .join(", ")
}

pub(crate) fn sql_script(
    ext: &str,
    version: &str,
    functions: &[Function],
    extra: &[(String, String)],
) -> String {
    let mut out = String::new();
    emit!(out, "-- Generated by sutegi-pgext from {ext} {version}.");
    emit!(
        out,
        "\\echo Use \"CREATE EXTENSION {ext}\" to load this file. \\quit"
    );
    for f in functions {
        let params = f
            .params
            .iter()
            .map(|p| format!("{} {}", ident(&p.name), p.sql_type))
            .collect::<Vec<_>>()
            .join(", ");
        emit!(out, "\n-- {} ({}:{})", f.rust_name, f.file, f.line);
        emit!(out, "CREATE FUNCTION {}({params})", ident(&f.sql_name));
        emit!(
            out,
            "RETURNS {}{}",
            if f.setof { "SETOF " } else { "" },
            f.returns
        );
        emit!(out, "AS 'MODULE_PATHNAME', '{}'", c_symbol(f));
        let mut attrs = vec!["LANGUAGE C".to_owned(), f.volatility.to_owned()];
        if f.strict {
            attrs.push("STRICT".into());
        }
        if f.leakproof {
            attrs.push("LEAKPROOF".into());
        }
        if f.security_definer {
            attrs.push("SECURITY DEFINER".into());
        }
        if let Some(p) = f.parallel {
            attrs.push(format!("PARALLEL {p}"));
        }
        if let Some(c) = f.cost {
            attrs.push(format!("COST {c}"));
        }
        if let Some(r) = f.rows {
            attrs.push(format!("ROWS {r}"));
        }
        // A SECURITY DEFINER function runs SPI queries with its owner's
        // rights: pin search_path, or a caller could shadow a table or
        // operator with an object in a schema they control.
        if f.security_definer {
            attrs.push("SET search_path = pg_catalog, pg_temp".into());
        }
        emit!(out, "{};", attrs.join(" "));
        if !f.doc.is_empty() {
            emit!(
                out,
                "COMMENT ON FUNCTION {}({}) IS {};",
                ident(&f.sql_name),
                signature_types(f),
                literal(&f.doc)
            );
        }
    }
    for (name, sql) in extra {
        emit!(out, "\n-- {name}\n{}", sql.trim_end());
    }
    out
}

fn c_string(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if c.is_ascii_graphic() || c == ' ' => out.push(c),
            _ => out.push('?'),
        }
    }
    out.push('"');
    out
}

pub(crate) fn functions_c(ext: &str, version: &str, functions: &[Function]) -> String {
    let mut out = String::new();
    emit!(
        out,
        "/* Generated by sutegi-pgext: the SQL functions PostgreSQL calls. */"
    );
    emit!(out, "#include \"sutegi_pgext.h\"\n");
    emit!(out, "#ifdef PG_MODULE_MAGIC_EXT");
    emit!(
        out,
        "PG_MODULE_MAGIC_EXT(.name = {}, .version = {});",
        c_string(ext),
        c_string(version)
    );
    emit!(out, "#else\nPG_MODULE_MAGIC;\n#endif");
    for f in functions {
        let sym = c_symbol(f);
        emit!(out, "\n/* {}({}) */", f.sql_name, signature_types(f));
        emit!(
            out,
            "extern void sutegi_pgext_fn_{}(sx_call *call);",
            f.rust_name
        );
        emit!(out, "PG_FUNCTION_INFO_V1({sym});");
        emit!(out, "Datum\n{sym}(PG_FUNCTION_ARGS)\n{{");
        emit!(
            out,
            "\treturn sx_invoke(fcinfo, sutegi_pgext_fn_{});\n}}",
            f.rust_name
        );
    }
    out
}

pub(crate) fn control(ext: &str, version: &str, comment: &str) -> String {
    format!(
        "# {ext} extension (generated by sutegi-pgext)\ncomment = {}\ndefault_version = {}\nmodule_pathname = '$libdir/{ext}'\nrelocatable = true\n",
        literal(comment),
        literal(version)
    )
}

/// The symbols the module exports: PostgreSQL's magic block and each SQL
/// function with its info function. Everything else — the C runtime and the
/// whole Rust static library — stays local, so two sutegi-pgext extensions
/// (each with its own copy of `sx_invoke` and of Rust's std) can be loaded
/// into one backend.
pub(crate) fn exports(functions: &[Function], macos: bool) -> String {
    let mut syms = vec!["Pg_magic_func".to_owned(), "_PG_init".to_owned()];
    for f in functions {
        let sym = c_symbol(f);
        syms.push(format!("pg_finfo_{sym}"));
        syms.push(sym);
    }
    if macos {
        syms.iter().map(|s| format!("_{s}\n")).collect()
    } else {
        let mut out = String::from("{\n  global:\n");
        for s in &syms {
            emit!(out, "    {s};");
        }
        out.push_str("  local: *;\n};\n");
        out
    }
}

pub(crate) struct MakefileInput<'a> {
    pub(crate) ext: &'a str,
    pub(crate) version: &'a str,
    pub(crate) staticlib: &'a str,
    pub(crate) native_libs: &'a str,
    pub(crate) pg_config: &'a str,
    pub(crate) macos: bool,
}

pub(crate) fn makefile(m: &MakefileInput<'_>) -> String {
    let exports = if m.macos {
        "-Wl,-exported_symbols_list,$(CURDIR)/exports.txt".to_owned()
    } else {
        "-Wl,--version-script=$(CURDIR)/exports.map -Wl,-Bsymbolic".to_owned()
    };
    format!(
        "# Generated by sutegi-pgext.\n\
         MODULE_big = {ext}\n\
         OBJS = sutegi_pgext.o functions.o\n\
         SHLIB_LINK += {lib} {libs} {exports}\n\
         EXTENSION = {ext}\n\
         DATA = {ext}--{version}.sql\n\
         PG_CONFIG = {pg_config}\n\
         PGXS := $(shell $(PG_CONFIG) --pgxs)\n\
         include $(PGXS)\n\
         # Relink when the Rust library changes, not only the C objects.\n\
         $(shlib): {lib}\n",
        ext = m.ext,
        version = m.version,
        lib = m.staticlib,
        libs = m.native_libs,
        pg_config = m.pg_config,
    )
}

#[cfg(test)]
mod tests {
    use super::super::scan::scan;
    use super::*;

    fn functions() -> Vec<Function> {
        scan(
            "src/lib.rs",
            r#"
/// It's a greeting.
#[pg_function(immutable, parallel_safe, cost = 5)]
fn hello(name: &str) -> String { todo!() }

#[pg_function(name = "maybe_double", leakproof, security_definer)]
fn maybe(x: Option<i64>, order: i32) -> Option<i64> { todo!() }
"#,
        )
        .unwrap()
    }

    #[test]
    fn sql_script_creates_each_function() {
        let sql = sql_script(
            "ext",
            "1.0",
            &functions(),
            &[("sql/extra.sql".into(), "SELECT 1;\n".into())],
        );
        assert_eq!(
            sql,
            "-- Generated by sutegi-pgext from ext 1.0.
\\echo Use \"CREATE EXTENSION ext\" to load this file. \\quit

-- hello (src/lib.rs:4)
CREATE FUNCTION \"hello\"(\"name\" text)
RETURNS text
AS 'MODULE_PATHNAME', 'sx_fn_hello'
LANGUAGE C IMMUTABLE STRICT PARALLEL SAFE COST 5;
COMMENT ON FUNCTION \"hello\"(text) IS 'It''s a greeting.';

-- maybe (src/lib.rs:7)
CREATE FUNCTION \"maybe_double\"(\"x\" bigint, \"order\" integer)
RETURNS bigint
AS 'MODULE_PATHNAME', 'sx_fn_maybe'
LANGUAGE C VOLATILE LEAKPROOF SECURITY DEFINER SET search_path = pg_catalog, pg_temp;

-- sql/extra.sql
SELECT 1;
"
        );
    }

    #[test]
    fn c_glue_routes_each_symbol_through_sx_invoke() {
        let c = functions_c("ext", "1.0", &functions());
        assert!(c.contains("PG_MODULE_MAGIC_EXT(.name = \"ext\", .version = \"1.0\");"));
        assert!(c.contains(
            "extern void sutegi_pgext_fn_hello(sx_call *call);\nPG_FUNCTION_INFO_V1(sx_fn_hello);"
        ));
        assert!(c.contains("return sx_invoke(fcinfo, sutegi_pgext_fn_maybe);"));
    }

    #[test]
    fn exports_list_only_the_sql_surface() {
        let linux = exports(&functions(), false);
        assert!(linux.contains("    pg_finfo_sx_fn_hello;\n    sx_fn_hello;\n"));
        assert!(linux.ends_with("  local: *;\n};\n"));
        assert_eq!(
            exports(&functions(), true).lines().next(),
            Some("_Pg_magic_func")
        );
    }

    #[test]
    fn control_quotes_the_comment() {
        assert!(control("ext", "1.0", "Bob's ext").contains("comment = 'Bob''s ext'\n"));
    }
}
